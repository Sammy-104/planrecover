import assert from 'node:assert/strict';
import {initialState,applyAction,normalizeWorkspace,tripList} from '../lib/model.ts';
import {planKind,validPlanDates} from '../lib/plan-types.ts';
import {sharedTripView,mergeSharedTrip,checkSharedAction} from '../lib/trip-sharing.ts';
import {itineraryStops} from '../lib/itinerary-map.ts';

const actor='sam',date='2027-04-04';
const create=(state,kind,name=kind,end=date)=>applyAction(state,{type:'create_trip',actor,plan:{kind,name,destination:'Toronto, Ontario, Canada',start:date,end,timezone:'America/Toronto',budget:5000}});
let state=initialState();delete state.plan.kind;
const original=structuredClone(state);
state=normalizeWorkspace(state);
assert.equal(state.plan.kind,'trip');assert.deepEqual(state.items,original.items);assert.deepEqual(state.events,original.events);
assert.ok(validPlanDates('day-out',date,date));assert.ok(!validPlanDates('day-out',date,'2027-04-05'));
assert.throws(()=>create(state,'day-out','Too long','2027-04-05'));
assert.throws(()=>create(state,'unknown'));
state=create(state,'day-out','Saturday in the city');const dayId=state.plan.id;
assert.equal(state.plan.kind,'day-out');assert.equal(state.plan.start,state.plan.end);assert.deepEqual(state.events,[]);
state=create(state,'event','Birthday dinner');const eventId=state.plan.id;
assert.equal(state.plan.kind,'event');assert.equal(tripList(state).length,3);
assert.deepEqual(tripList(normalizeWorkspace(JSON.parse(JSON.stringify(state)))).map(p=>planKind(p.plan)),['event','day-out','trip']);
// Preparation can be due before the event. A task does not create a booking, payment or map stop.
const task={type:'add_item',actor,name:'Order the cake',category:'Preparation',start:'2027-04-02T10:00:00-04:00',duration:20,price:0,participants:['maya'],taskOwner:'maya'};
state=applyAction(state,task);const taskId=state.items[0].id;
assert.equal(state.items[0].taskOwner,'maya');assert.equal(state.items[0].status,'scheduled');assert.deepEqual(state.events,[]);assert.deepEqual(itineraryStops(state),[]);
assert.throws(()=>applyAction(state,{...task,taskOwner:'unknown'}));
assert.throws(()=>applyAction(state,{...task,start:'2027-04-05T10:00:00-04:00'}));
assert.throws(()=>applyAction(state,{...task,category:'Activity'}));
state=applyAction(state,{type:'add_item',actor,name:'Dinner venue',category:'Meal',start:'2027-04-04T18:00:00-04:00',duration:90,price:null,participants:['sam','maya']});
Object.assign(state.items[1],{latitude:43.65,longitude:-79.38});assert.equal(itineraryStops(state).length,1);
const guest=sharedTripView(state,eventId);assert.equal(guest.plan.kind,'event');assert.deepEqual(guest.archives,[]);
const action={type:'task',actor:'maya',itemId:taskId,done:true};checkSharedAction(guest,action);
const updated=applyAction(guest,action);state=mergeSharedTrip(state,updated,eventId);
assert.equal(state.items[0].done,true);assert.deepEqual(state.events,[]);
state=applyAction(state,{type:'select_trip',actor,tripId:dayId});
const merged=mergeSharedTrip(state,updated,eventId);assert.equal(merged.plan.kind,'day-out');assert.equal(merged.archives.find(p=>p.id===eventId).workspace.items[0].done,true);
for(const type of ['delete_trip','create_trip','select_trip'])assert.throws(()=>checkSharedAction(guest,{type,actor}));
const deleted=applyAction(merged,{type:'delete_trip',actor,deleteTripId:eventId,confirmed:true});
assert.equal(tripList(deleted).length,2);assert.equal(deleted.plan.kind,'day-out');
console.log('Plan types: legacy migration, single-day rules, persistence, assigned tasks before events, financial/map isolation, shared edits, switching and deletion passed.');
