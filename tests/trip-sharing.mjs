import assert from 'node:assert/strict';
import {initialState,applyAction} from '../lib/model.ts';
import {sharedTripView,mergeSharedTrip,checkSharedAction} from '../lib/trip-sharing.ts';
const actor='sam';
let root=applyAction(initialState(),{type:'create_trip',actor,plan:{name:'Lisbon with friends',destination:'Lisbon, Portugal',start:'2027-04-04',end:'2027-04-06',budget:30000}});
const tripId=root.plan.id,otherId=root.archives[0].workspace.plan.id;
const view=sharedTripView(root,tripId);
assert.deepEqual(view.archives,[]);
assert.equal(view.version,root.version);
const edited=applyAction(view,{type:'plan',actor,plan:{...view.plan,name:'Our Lisbon trip'}});
const activeMerge=mergeSharedTrip(root,edited,tripId);
assert.equal(activeMerge.plan.name,'Our Lisbon trip');
assert.deepEqual(activeMerge.archives,root.archives,'Shared edits preserve other trips');
root=applyAction(root,{type:'select_trip',actor,tripId:otherId});
const archivedMerge=mergeSharedTrip(root,edited,tripId);
assert.deepEqual(archivedMerge.plan,root.plan,'A friend cannot replace the owner’s active trip');
assert.equal(archivedMerge.archives.find(a=>a.workspace.plan.id===tripId).workspace.plan.name,'Our Lisbon trip');
for(const type of ['reset','create_trip','select_trip','delete_trip'])assert.throws(()=>checkSharedAction(view,{type,actor}));
assert.throws(()=>checkSharedAction(view,{type:'plan',actor,plan:{...view.plan,destination:'Tokyo, Japan'}}));
assert.doesNotThrow(()=>checkSharedAction(view,{type:'plan',actor,plan:{...view.plan,name:'Changed together'}}));
assert.throws(()=>mergeSharedTrip(root,{...edited,plan:root.plan},tripId));
assert.throws(()=>sharedTripView(root,'unknown-trip'));
console.log('Shared-trip scope, active and saved trip edits, owner-only controls and workspace isolation passed.');
